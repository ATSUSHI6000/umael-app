def safe_int(val, default=0):
    try:
        if isinstance(val, (pd.Series, list)):
            val = val[0] if len(val) > 0 else default
        num = pd.to_numeric(val, errors='coerce')
        if pd.isna(num):
            return default
        return int(num)
    except Exception:
        return default


